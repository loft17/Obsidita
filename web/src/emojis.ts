// Quita tildes y pasa a minúsculas para comparar sin depender de acentos
const normalize = (s: string) =>
  s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase();

// Devuelve los emojis cuyas palabras clave contienen todas las palabras de la búsqueda
export function searchEmojis(query: string): string[] {
  const words = normalize(query.trim()).split(/\s+/).filter(Boolean);
  if (!words.length) return EMOJIS.map(([emoji]) => emoji);
  return EMOJIS.filter(([, keys]) => {
    const text = normalize(keys);
    return words.every((w) => text.includes(w));
  }).map(([emoji]) => emoji);
}
